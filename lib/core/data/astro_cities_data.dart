/// ASTRAL Phase 1 — offline city catalog for natal chart birth data.
/// City-center coordinates, localized names, and historical IANA zone IDs.
library;

import '../l10n/app_strings.dart';

/// One searchable city with chart-relevant data.
class AstroCity {
  const AstroCity({
    this.id = -1,
    this.nameKey,
    this.literalName,
    this.countryKey,
    this.literalCountry,
    required this.latitude,
    required this.longitude,
    required this.timezoneOffsetHours,
    this.timezoneId,
  });

  /// Stable index in [astroCities]; -1 for a manually entered location.
  final int id;
  final String? nameKey;
  final String? countryKey;

  /// Used for a location typed by the reader (never translated).
  final String? literalName;
  final String? literalCountry;

  /// North positive, degrees.
  final double latitude;

  /// East positive, degrees.
  final double longitude;

  final String? timezoneId;

  /// Fallback offset for legacy and manually specified locations.
  final double timezoneOffsetHours;

  String get name =>
      nameKey != null ? AppStrings.g(nameKey!) : (literalName ?? '');

  String get country =>
      countryKey != null ? AppStrings.g(countryKey!) : (literalCountry ?? '');

  /// The English name, used by the search so a reader can type either one.
  String get englishName =>
      nameKey != null ? AppStrings.t(AppLanguage.en, nameKey!) : name;

  /// Every localized spelling, so `биш`, `bish` and `bis` all find Bishkek.
  Iterable<String> get searchNames => nameKey == null
      ? [name]
      : [
          for (final language in AppLanguage.values)
            AppStrings.t(language, nameKey!),
        ];
}

